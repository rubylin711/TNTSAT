Buffer* Buffer::ReleaseChain(Buffer* chain)
{
    //Release given list of buffers
    while (chain)
    {
        Buffer* next = chain->Next;

        chain->Next = NULL;
        chain->Release();

        chain = next;
    }
    return chain;
}

