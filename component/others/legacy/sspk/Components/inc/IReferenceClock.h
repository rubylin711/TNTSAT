// ===============================================================================================================
// IReferenceClock - provides a common reference clock for all streams
// ===============================================================================================================

class IReferenceClock
{
public:
    //Destructor
    virtual ~IReferenceClock() {}
    //Returns time in 10Mhz unit
    virtual uint64  GetTime(void) = 0;
    //returns time in 32.32 FP units
    virtual uint64  GetTimeEx(void) = 0;
};

