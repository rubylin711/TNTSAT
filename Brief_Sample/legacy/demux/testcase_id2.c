mt_s32 parse_cmdline(mt_char *pCmdLine, mt_s32 *pArgc, mt_char Argv[MAX_ARGS_COUNT][MAX_ARGS_LEN])
{
    mt_char *ptr = pCmdLine;
    int i;
    while ((*ptr == ' ') && (*ptr++ != '\0'))
    {
	;
    }

    for (i = strlen(ptr); i > 0; i--) {
	if ((*(ptr + i - 1) == 0x0a) || (*(ptr + i - 1) == ' ')) {
	    *(ptr + i - 1) = '\0';
	} else {
	    break;
	}
    }

    for (i = 0; i < MAX_ARGS_COUNT; i++) {
	int j = 0;
	while ((*ptr == ' ') && (*(++ptr) != '\0')) {
	    ;
	}

	while ((*ptr != ' ') && (*ptr != '\0') && (j < MAX_ARGS_LEN)) {
	    Argv[i][j++] = *ptr++;
	}

	Argv[i][j] = '\0';
	if ('\0' == *ptr) {
	    i++;
	    break;
	}
    }
    *pArgc = i;

    return MT_SUCCESS;
}

