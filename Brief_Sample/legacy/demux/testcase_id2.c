    Ret = MT_UNF_DMX_CreateDescramblerExt(0, &stNorcaDescAttr, &g_hNorca_CSA3_Desc);
    if (MT_SUCCESS != Ret) {
	g_hNorca_CSA3_Desc = INVALID_HANDLE;
    }

#if 0
    //CSA3.0 hadvca
    memset(&stAdvcaDescAttr,0,sizeof(MT_UNF_DMX_DESCRAMBLER_ATTR_S));
    stAdvcaDescAttr.enCaType = MT_UNF_DMX_CA_ADVANCE;
    stAdvcaDescAttr.enDescramblerType = MT_UNF_DMX_DESCRAMBLER_TYPE_CSA3;
    Ret = MT_UNF_DMX_CreateDescramblerExt(0,&stAdvcaDescAttr,&g_hAdvca_CSA3_Desc);
    if (MT_SUCCESS != Ret)
    {
      g_hAdvca_CSA3_Desc = INVALID_HANDLE;
    }
#endif
/*
    Ret = MTADP_Tuner_Init();
    if (MT_SUCCESS != Ret)
    {
      printf("call MTADP_Demux_Init failed.\n");
      goto DES_DESTROY;
    }
    */
#if 0

    Ret = MTADP_Tuner_Connect(TUNER_USE,g_TunerFreq,g_TunerSrate,g_TunerQam);
    if (MT_SUCCESS != Ret)
    {
      printf("call MTADP_Tuner_Connect failed.\n");
      goto TUNER_DEINIT;
    }
#endif
#if 0
    MTADP_Search_Init();
    Ret = MTADP_Search_GetAllPmt(0,&g_pProgTbl);
    if (MT_SUCCESS != Ret)
    {
      printf("call MTADP_Search_GetAllPmt failed\n");
      goto PSISI_FREE;
    }
#endif
    Ret = MTADP_AVPlay_RegADecLib();
    Ret |= MT_UNF_AVPLAY_Init();
    if (Ret != MT_SUCCESS) {
	printf("call MT_UNF_AVPLAY_Init failed.\n");
	goto PSISI_FREE;
    }

    Ret = MT_UNF_AVPLAY_GetDefaultConfig(&AvplayAttr, MT_UNF_AVPLAY_STREAM_TYPE_TS);
    Ret |= MT_UNF_AVPLAY_Create(&AvplayAttr, &g_hAvplay);
    if (Ret != MT_SUCCESS) {
	printf("call MT_UNF_AVPLAY_Create failed.\n");
	goto AVPLAY_DEINIT;
    }

    Ret = MT_UNF_DMX_AttachTSPort(0, MT_UNF_DMX_PORT_RAM_0);
    Ret |= MT_UNF_AVPLAY_ChnOpen(g_hAvplay, MT_UNF_AVPLAY_MEDIA_CHAN_VID, MT_NULL);
    printf("MT_UNF_AVPLAY_ChnOpen :: VID  Ret = 0x%x\n", Ret);
    if (MT_SUCCESS != Ret) {
	printf("call MT_UNF_AVPLAY_ChnOpen failed.\n");
	goto CHN_CLOSE;
    }

    Ret = MT_UNF_DMX_AttachTSPort(0, MT_UNF_DMX_PORT_TSI_1);
