	    //printf("fread ..........%x...........%x.....\n", g_pTsFile, StreamBuf.pu8Data);
	    //Readlen = fread(StreamBuf.pu8Data, sizeof(mt_s8), INJECT_DATA_LEN, g_pTsFile);
	    Readlen = RecData.u32Len;
