/*
hmac [-t] auto level
hmac [-t] sha256 level
*/
static int mss_hmac_test_auto(int argc, char *const argv[])
{
    mt_s32 ret = 0;
    MSS_CPU_MODE_E cpu_mode = MSS_APCPU;
    mt_u32 level;
    mt_u32 idx;
    mt_u32 type = 0xff;
    char *cmd;
    mt_u32 i;
    struct mss_hmac_data *testcase;

    idx = 0;
    if (strcmp(argv[idx], "-t") == 0) {
        cpu_mode = MSS_SECCPU;
        idx++;
    }

    cmd = argv[idx++];
    if (0 == strncmp("auto", cmd, 4)){
        type = 0xff;
    } else if (0 == strncmp("sha256", cmd, 6)) {
        type = MT_CIPHER_MAC_TYPE_SHA256;
    } else if (0 == strncmp("sha224", cmd, 6)) {
        type = MT_CIPHER_MAC_TYPE_SHA224;
    } else if (0 == strncmp("sha384", cmd, 6)) {
        type = MT_CIPHER_MAC_TYPE_SHA384;
    } else if (0 == strncmp("sha512", cmd, 6)) {
        type = MT_CIPHER_MAC_TYPE_SHA512;
    } else if (0 == strncmp("sm3", cmd, 3)) {
        type = MT_CIPHER_MAC_TYPE_SM3;
    } else if (0 == strncmp("cmacaes", cmd, 7)) {
        type = MT_CIPHER_MAC_TYPE_CMAC_AES128;
    } else if (0 == strncmp("cmacsm4", cmd, 7)) {
        type = MT_CIPHER_MAC_TYPE_CMAC_SM4;
    }

    level = (mt_u32)strtol(argv[idx++], NULL, 0);

    for (i = 0; i < ARRAY_SIZE(mss_hmac_testcase); i++) {
        testcase = &mss_hmac_testcase[i];
        if (type == 0xff || type == testcase->type) {
            if (cpu_mode == MSS_APCPU)
                ret = mss_hmac_ree_test(testcase, level);
            else {
                if (testcase->key_length <= 32) {
                    ret = mss_hmac_tee_test(testcase, level);
                }
            }

            if (ret != 0)
                return ret;
        }
    }

    return 0;
}

