static int mss_hmac_ree_test(struct mss_hmac_data *testcase, mt_u32 update_cnt)
{
    mt_s32 ret = 0;
    mt_u8 mac[64];
    mt_handle handle;
    mt_u8 key_tmp[32];
    mt_u8 *key;
    mt_u32 key_len;
    mt_u8 *msg;
    mt_u32 msg_len;
    mt_u32 update_len;
    mt_u32 cnt;
    mt_u8 *expect_mac;
    mt_u32 mac_len;
    MT_KT_CTRL_S ctrl;
    MT_CIPHER_MAC_TYPE_E hmac_type;
    MT_CIPHER_HMAC_ATTS_S hmac_attr;
    mt_u8 rand;
    mt_u32 kt_support = 1;
    
    key_len = testcase->key_length;
    expect_mac = testcase->mac;
    mac_len = testcase->mac_length;
    hmac_type = testcase->type;

    printf("\n=============== ");

    switch (hmac_type) {
    case MT_CIPHER_MAC_TYPE_SHA256:
        printf("HMAC SHA256");
        break;
    case MT_CIPHER_MAC_TYPE_SHA224:
        printf("HMAC SHA224");
        break;
    case MT_CIPHER_MAC_TYPE_SHA384:
        printf("HMAC SHA384");
        break;
    case MT_CIPHER_MAC_TYPE_SHA512:
        printf("HMAC SHA512");
        break;
    case MT_CIPHER_MAC_TYPE_SM3:
        printf("HMAC SM3");
        break;
    case MT_CIPHER_MAC_TYPE_CMAC_AES128:
        printf("CMAC AES128");
        break;
    case MT_CIPHER_MAC_TYPE_CMAC_SM4:
        printf("CMAC SM4");
        break;
    default:
        printf("UNKNOWN mac type\n");
        return -1;
    }
    printf(" ===============\n");

    printf("  update_cnt: %d  key_len:%d\n", update_cnt, key_len);

    memset(&hmac_attr, 0, sizeof(hmac_attr));
    hmac_attr.key_slot[0] = MT_CIPHER_KEYSLOT_INVALID;
    hmac_attr.key_slot[1] = MT_CIPHER_KEYSLOT_INVALID;

    memset(&ctrl, 0, sizeof(ctrl));
    ctrl.purpose = MT_KT_PURPOSE_M2M | MT_KT_PURPOSE_MAC;
    ctrl.operation = MT_KT_OPERATION_ENCRYPT;

    if (hmac_type == MT_CIPHER_MAC_TYPE_CMAC_AES128)
        ctrl.algorithm = MT_KT_ALG_AES;
    else if (hmac_type == MT_CIPHER_MAC_TYPE_CMAC_SM4)
        ctrl.algorithm = MT_KT_ALG_SM4;

    if (key_len > 32) {
        kt_support = 0;
    } else if (key_len > 16){
        /* 256key */
        if (key_len == 32) {
            key = testcase->key;
        }
        else {
            memset(key_tmp, 0, 32);
            memcpy(key_tmp, testcase->key, key_len);
            key = key_tmp;
        }
        ctrl.keysize = MT_KT_KEYSIZE_256;

        ret = mt_unf_cipher_keyslot_request_multi(2, hmac_attr.key_slot);
    } else {
        /* 128key */
        if (key_len == 16)
            key = testcase->key;
        else {
            memset(key_tmp, 0, 16);
            memcpy(key_tmp, testcase->key, key_len);
            key = key_tmp;
        }
        ctrl.keysize = MT_KT_KEYSIZE_128;

        ret = mt_unf_cipher_keyslot_request_multi(1, hmac_attr.key_slot);
    }

    if (kt_support) {
        printf("\nmac test with KEYSLOT\n");

        hmac_attr.p_hmac_key = NULL;

        mt_unf_cipher_keyslot_set_ext(hmac_attr.key_slot[0], &ctrl, key, NULL);

        hmac_attr.key_len = 16;
        mt_unf_cipher_keyslot_info(hmac_attr.key_slot[0]);
        if (hmac_attr.key_slot[1] != MT_CIPHER_KEYSLOT_INVALID) {
            mt_unf_cipher_keyslot_info(hmac_attr.key_slot[1]);
            hmac_attr.key_len = 32;
        }
        mss_dump("kt key", key, hmac_attr.key_len);
    
        ret = mt_unf_cipher_mac_create(hmac_type, &hmac_attr, &handle);
        if (ret != MT_SUCCESS) {
            printf("mt_unf_cipher_mac_create fail %d\n", ret);

            if (hmac_attr.key_slot[0] != MT_CIPHER_KEYSLOT_INVALID)
                mt_unf_cipher_keyslot_release(hmac_attr.key_slot[0]);
            if (hmac_attr.key_slot[1] != MT_CIPHER_KEYSLOT_INVALID)
                mt_unf_cipher_keyslot_release(hmac_attr.key_slot[1]);
            return ret;
        }

        cnt = update_cnt;
        msg = testcase->msg;
        update_len = testcase->msg_length;

        while (cnt > 0) {
            cnt--;

            if (cnt == 0) {
                msg_len = update_len;
            } else {
                mt_unf_cipher_get_random_number(1, &rand);
                //rand = 64;
                msg_len = rand % (update_len - cnt);
            }

            mss_dump("msg", msg, msg_len);
            ret |= mt_unf_cipher_mac_update(handle, msg, msg_len);

            msg += msg_len;
            update_len -= msg_len;
        }

        ret |= mt_unf_cipher_mac_final(handle, mac);

        if (hmac_attr.key_slot[0] != MT_CIPHER_KEYSLOT_INVALID) {
            mt_unf_cipher_keyslot_release(hmac_attr.key_slot[0]);
            hmac_attr.key_slot[0] = MT_CIPHER_KEYSLOT_INVALID;
        }
        if (hmac_attr.key_slot[1] != MT_CIPHER_KEYSLOT_INVALID) {
            mt_unf_cipher_keyslot_release(hmac_attr.key_slot[1]);
            hmac_attr.key_slot[1] = MT_CIPHER_KEYSLOT_INVALID;
        }

        mss_dump("mac", mac, mac_len);
        if (memcmp(mac, expect_mac, mac_len) != 0) {
            printf("========== HMAC KT FAIL ==========\n");
            mss_dump("expect", expect_mac, mac_len);
            return -1;
        }
        printf("========== HMAC KT SUCCESS ==========\n");
    }

    {
        printf("\nmac test with DIRECT KEY\n");

        mss_dump("direct key", testcase->key, testcase->key_length);

        hmac_attr.p_hmac_key = testcase->key;
        hmac_attr.key_len = testcase->key_length;
        hmac_attr.key_slot[0] = MT_CIPHER_KEYSLOT_INVALID;
        hmac_attr.key_slot[1] = MT_CIPHER_KEYSLOT_INVALID;

        ret = mt_unf_cipher_mac_create(hmac_type, &hmac_attr, &handle);
        if (ret != MT_SUCCESS) {
            printf("mt_unf_cipher_mac_create fail\n");
            return ret;
        }

        cnt = update_cnt;
        msg = testcase->msg;
        update_len = testcase->msg_length;

        while (cnt > 0) {
            cnt--;

            if (cnt == 0) {
                msg_len = update_len;
            } else {
                mt_unf_cipher_get_random_number(1, &rand);
                //rand = 64;
                msg_len = rand % (update_len - cnt);
            }

            mss_dump("msg", msg, msg_len);
            ret |= mt_unf_cipher_mac_update(handle, msg, msg_len);

            msg += msg_len;
            update_len -= msg_len;
        }

        ret |= mt_unf_cipher_mac_final(handle, mac);

        mss_dump("mac", mac, mac_len);
        if (memcmp(mac, expect_mac, mac_len) != 0) {
            printf("========== HMAC DIRECT FAIL ==========\n");
            mss_dump("expect", expect_mac, mac_len);
            return -1;
        }
        printf("========== HMAC DIRECT SUCCESS ==========\n");

    }

    return 0;
}

